"""Bundles src/*.py into one Kaggle script kernel (private, no internet, competition data attached) that runs the
given shell commands in /kaggle/working and prints every results/*.txt at the end.
Usage: python3 kaggle/make_kernel.py <slug> "<cmd1>" "<cmd2>" ...   (commands run from /kaggle/working)
Then:  kaggle kernels push -p kaggle/kernels/<slug>"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
slug, cmds = sys.argv[1], sys.argv[2:]
srcs = {p.name: p.read_text() for p in sorted((ROOT / "src").glob("*.py"))}
# selected validation configurations travel with the code, so the final kernel uses exactly the logged choices
cfgs = {p.name: p.read_text() for p in sorted((ROOT / "results").glob("val_*_best.json"))}
run = f'''# Generated by kaggle/make_kernel.py from the repository's src/ (hse-llm4rec-exam-sweettv).
import glob, json, os, pathlib, subprocess, sys, time
W = pathlib.Path("/kaggle/working")
(W / "src").mkdir(exist_ok=True); (W / "results").mkdir(exist_ok=True)
for name, code in json.loads({json.dumps(json.dumps(srcs))}).items():
    (W / "src" / name).write_text(code)
for name, txt in json.loads({json.dumps(json.dumps(cfgs))}).items():
    (W / "results" / name).write_text(txt)
data = os.path.dirname(glob.glob("/kaggle/input/**/dataset11-30.csv", recursive=True)[0])
env = dict(os.environ, SWEETTV_DATA=data, SWEETTV_CACHE=str(W / "cache"), PYTHONWARNINGS="ignore")
print("data dir:", data, "| python", sys.version.split()[0], flush=True)
subprocess.run("python -c 'import numpy, pandas, scipy, sklearn; print(\\"numpy\\", numpy.__version__, \\"pandas\\", pandas.__version__, \\"scipy\\", scipy.__version__, \\"sklearn\\", sklearn.__version__)'; nproc; free -g | head -2", shell=True, cwd=W, env=env)
for cmd in {json.dumps(cmds)}:
    t0 = time.time(); print("\\n$", cmd, flush=True)
    r = subprocess.run(cmd, shell=True, cwd=W, env=env)
    print(f"[exit {{r.returncode}} after {{time.time() - t0:.0f}}s]", flush=True)
for f in sorted((W / "results").glob("*.txt")):
    print("\\n=== results/" + f.name + " ===\\n" + f.read_text(), flush=True)
'''
d = ROOT / "kaggle" / "kernels" / slug
d.mkdir(parents=True, exist_ok=True)
(d / "run.py").write_text(run)
(d / "kernel-metadata.json").write_text(json.dumps({
    "id": f"shmate/{slug}", "title": slug, "code_file": "run.py", "language": "python", "kernel_type": "script",
    "is_private": True, "enable_gpu": False, "enable_internet": False,
    "competition_sources": ["sweettv-tv-program-recommender"], "dataset_sources": [], "kernel_sources": []}, indent=1))
print(f"wrote {d}/run.py ({len(run):,} bytes, {len(srcs)} modules) and kernel-metadata.json")
